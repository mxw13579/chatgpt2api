export async function updateSettingsConfig(settings: SettingsConfig) {
  // 图片存储只能通过专用接口保存；基础设置/备份等不能回写旧 R2 快照。
  const body = { ...settings };
  delete body.image_storage;
  return httpRequest<{ config: SettingsConfig }>("/api/settings", {
    method: "POST",
    body,
  });
}

